#!/usr/bin/env python3
"""產生「成員作品」：portfolio/index.html 的作品卡片，以及每個作品的案例頁 portfolio/{slug}.html。

用法：  pip install markdown-it-py   &&   python3 tools/build_works.py
輸入：  tools/works.json（由 tools/sync_notion.py 從 Notion「作品」資料庫產生）、tools/posts.json（相關文章）
輸出：  portfolio/（提交它；GitHub Pages 直接使用）

- portfolio/index.html 只會改 <!-- WORKS:START --> 與 <!-- WORKS:END --> 之間的內容，其餘手寫部分不動。
- 案例頁開頭有 <!-- generated by build_works --> 標記；已下架作品的案例頁會被清掉，沒有這個標記的檔案不會被動到。
- 作品的圖片放在 portfolio/img/（同步時自動處理）。
"""
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))  # 讓 python -I 或別的資料夾執行時也找得到 build_blog
import build_blog as B  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "portfolio"
IMG = OUT / "img"
MARK = "<!-- generated by build_works -->"
START, END = "<!-- WORKS:START -->", "<!-- WORKS:END -->"
esc = B.esc

works_path = ROOT / "tools" / "works.json"
works = json.loads(works_path.read_text(encoding="utf8")) if works_path.exists() else []
works.sort(key=lambda w: (w.get("order") if w.get("order") is not None else 9999, w["title"]))

# 專案進度的顏色（Tailwind class 直接寫在產生的 HTML 裡）
PROGRESS = {
    "概念驗證": "bg-amber-100 text-amber-700 border-amber-200 dark:bg-amber-500/15 dark:text-amber-300 dark:border-amber-500/30",
    "開發中": "bg-sky-100 text-sky-700 border-sky-200 dark:bg-sky-500/15 dark:text-sky-300 dark:border-sky-500/30",
    "測試中": "bg-violet-100 text-violet-700 border-violet-200 dark:bg-violet-500/15 dark:text-violet-300 dark:border-violet-500/30",
    "已上線": "bg-emerald-100 text-emerald-700 border-emerald-200 dark:bg-emerald-500/15 dark:text-emerald-300 dark:border-emerald-500/30",
    "已結案": "bg-slate-200 text-slate-600 border-slate-300 dark:bg-slate-500/20 dark:text-slate-300 dark:border-slate-500/40",
}
TAG = "inline-block text-xs px-2 py-0.5 rounded-md bg-slate-100 text-slate-600 dark:bg-slate-700/60 dark:text-slate-300"
LINK = "text-sky-600 dark:text-sky-400 hover:underline"
ACTIVE = "text-sky-600 dark:text-sky-400 font-semibold"
INACTIVE = "text-slate-600 hover:text-sky-500 dark:text-slate-300 dark:hover:text-sky-400 transition-colors"


def badge(w):
    cls = PROGRESS.get(w.get("progress"), PROGRESS["已結案"])
    return f'<span class="inline-block text-xs px-2.5 py-1 rounded-full border {cls}">{esc(w["progress"])}</span>' if w.get("progress") else ""


def tags(w):
    return "".join(f'<span class="{TAG}">{esc(t)}</span>' for t in w.get("tags", []))


def links(w):
    out = []
    if w.get("github"):
        out.append(f'<a href="{esc(w["github"])}" target="_blank" rel="noopener noreferrer" class="{LINK}"><i class="fab fa-github mr-1"></i>GitHub</a>')
    if w.get("live"):
        out.append(f'<a href="{esc(w["live"])}" target="_blank" rel="noopener noreferrer" class="{LINK}"><i class="fas fa-arrow-up-right-from-square mr-1"></i>成品</a>')
    return out


def first_image(w):
    for ln in w["md"].split("\n"):
        m = B.IMG_RE.match(ln.strip())
        if m and (IMG / m.group(1)).exists():
            return m.group(1), (m.group(2) or "").strip()
    return None


def card(w):
    img = first_image(w)
    if img:
        thumb = f'<img src="img/{esc(img[0])}" alt="{esc(img[1] or w["title"])}" class="w-full h-48 object-cover object-top" loading="lazy">'
    else:
        thumb = '<div class="w-full h-48 flex items-center justify-center text-5xl bg-gradient-to-br from-sky-100 to-indigo-100 dark:from-sky-900/40 dark:to-indigo-900/40">🧪</div>'
    extra = links(w)
    extra_html = f'<div class="flex gap-4 text-sm mt-3">{"".join(extra)}</div>' if extra else ""
    return (
        '<article class="glass-card rounded-2xl overflow-hidden bg-white/70 dark:bg-[rgba(30,41,59,0.7)] border border-slate-200 '
        'dark:border-[rgba(255,255,255,0.1)] shadow-lg shadow-slate-200/50 dark:shadow-none flex flex-col">'
        f'<a href="{esc(w["slug"])}.html" aria-label="{esc(w["title"])}">{thumb}</a>'
        '<div class="p-6 flex flex-col flex-1">'
        f'<div class="mb-3">{badge(w)}</div>'
        f'<h3 class="text-lg font-bold text-slate-900 dark:text-white mb-2"><a href="{esc(w["slug"])}.html" class="hover:text-sky-500 transition-colors">{esc(w["title"])}</a></h3>'
        f'<p class="text-slate-600 dark:text-slate-400 text-sm leading-relaxed mb-4">{esc(w["summary"])}</p>'
        f'<div class="flex flex-wrap gap-1.5 mb-4">{tags(w)}</div>'
        '<div class="mt-auto">'
        f'<a href="{esc(w["slug"])}.html" class="text-sm font-medium {LINK}">看案例 <i class="fas fa-arrow-right ml-1"></i></a>'
        f'{extra_html}</div></div></article>'
    )


EMPTY = (
    '<div class="reveal rounded-2xl p-12 text-center bg-white/70 dark:bg-[rgba(30,41,59,0.7)] border border-dashed border-slate-300 dark:border-slate-600">\n'
    '                    <div class="text-5xl mb-4">🗂️</div>\n'
    '                    <h2 class="text-xl font-bold text-slate-900 dark:text-white mb-2">作品整理中</h2>\n'
    '                    <p class="text-slate-600 dark:text-slate-400">之後會在這裡放上作品截圖、說明，以及 GitHub 或成品連結。</p>\n'
    '                </div>'
)


def build_index():
    f = OUT / "index.html"
    html = f.read_text(encoding="utf8")
    if START not in html or END not in html:
        raise SystemExit("portfolio/index.html 找不到 <!-- WORKS:START --> / <!-- WORKS:END --> 標記")
    if works:
        inner = '<div class="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-6">\n' + "\n".join(card(w) for w in works) + "\n                </div>"
    else:
        inner = EMPTY
    new = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda m: f"{START}\n                {inner}\n                {END}", html, flags=re.S)
    if new != html:
        f.write_text(new, encoding="utf8")


def related_posts(w):
    by_notion = {p.get("notion"): p for p in B.posts if p.get("notion")}  # B.posts 已排除 hidden_ids
    return [by_notion[n] for n in w.get("related", []) if n in by_notion]


def build_case(w):
    p = {"id": w["slug"], "title": w["title"], "date": "2026-01-01", "md": w["md"]}  # date 只用來決定換行方式
    body_html = B.render_body(p, img_dir=IMG, img_src="img/", where="portfolio/img")
    meta = [x for x in (badge(w), tags(w)) if x]
    ln = links(w)
    rel = related_posts(w)
    rel_html = ""
    if rel:
        items = "".join(
            f'<li><a href="../blog/posts/{r["id"]}.html" class="{LINK}">{esc(r["title"])}</a>'
            f'<span class="text-slate-500 dark:text-slate-400 text-sm ml-2">{r["date"]}</span></li>' for r in rel)
        rel_html = (f'<section class="mt-14 pt-6 border-t border-slate-200 dark:border-slate-700">'
                    f'<h2 class="text-lg font-bold text-slate-900 dark:text-white mb-3">開發過程記錄</h2>'
                    f'<p class="text-sm text-slate-500 dark:text-slate-400 mb-3">更完整的開發筆記放在個人空間。</p>'
                    f'<ul class="space-y-2">{items}</ul></section>')
    body = f"""<main class="max-w-3xl mx-auto px-6 pt-28">
<a href="index.html" class="text-sm text-slate-500 dark:text-slate-400 hover:text-sky-500"><i class="fas fa-arrow-left mr-1"></i>返回成員作品</a>
<article class="mt-6">
<div class="flex flex-wrap items-center gap-2 mb-4">{"".join(meta)}</div>
<h1 class="text-2xl md:text-4xl font-bold text-slate-900 dark:text-white leading-snug mb-4">{esc(w['title'])}</h1>
<p class="text-slate-600 dark:text-slate-400 leading-relaxed mb-4">{esc(w['summary'])}</p>
{('<div class="flex gap-4 text-sm mb-8">' + "".join(ln) + '</div>') if ln else '<div class="mb-8"></div>'}
<div class="post-body text-slate-700 dark:text-slate-300">
{body_html}
</div>
</article>
{rel_html}
</main>
"""
    html = B.page(f"{w['title']} | JP 的作品", w["summary"], "../", body)
    # 導覽列：高亮「成員作品」，不是「成員個人空間」
    html = html.replace(f'href="../portfolio/index.html" class="{INACTIVE}"', f'href="../portfolio/index.html" class="{ACTIVE}"', 1)
    html = html.replace(f'href="../blog/index.html" class="{ACTIVE}"', f'href="../blog/index.html" class="{INACTIVE}"', 1)
    (OUT / f"{w['slug']}.html").write_text(MARK + "\n" + html, encoding="utf8")


def main():
    keep = {w["slug"] + ".html" for w in works}
    for f in OUT.glob("*.html"):  # 清掉已下架作品的案例頁（只動有標記的）
        if f.name != "index.html" and f.name not in keep and f.read_text(encoding="utf8").startswith(MARK):
            f.unlink()
    for w in works:
        build_case(w)
    build_index()
    print(f"built {len(works)} works")


if __name__ == "__main__":
    main()
